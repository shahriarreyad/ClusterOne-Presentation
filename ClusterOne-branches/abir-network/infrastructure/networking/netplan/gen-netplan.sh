#!/usr/bin/env bash
# gen-netplan.sh — render one netplan file per node from inventory/ (N2.3).
#
#   netplan/gen-netplan.sh            # writes netplan/<host>.yaml for every node
#   OOB=1 netplan/gen-netplan.sh      # anchor also gets the VLAN 9 switch-management leg
#                                     #   (managed switch only — see switch/README.md)
#
# Never type netplan by hand on a box (risk R5). Edit inventory/, re-run, commit, deploy
# with Ansible. Deploy with `netplan try`, never a blind `netplan apply` over SSH.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NODES="$HERE/../inventory/nodes.csv"
IFACES="$HERE/../inventory/interfaces.csv"
ANCHOR_IP="${ANCHOR_IP:-10.42.0.10}"
DOMAIN="${DOMAIN:-clusterone.internal}"
OOB="${OOB:-0}"
OOB_ADDR="${OOB_ADDR:-10.42.9.2/29}"

# field <csv> <shortname> <column-number>
field() { awk -F, -v n="$2" -v c="$3" '$1==n && $1 !~ /^#/ {print $c}' "$1"; }

header() {
  echo "# GENERATED by netplan/gen-netplan.sh from inventory/*.csv — do not edit by hand."
  echo "network:"
  echo "  version: 2"
  echo "  renderer: networkd"
  echo "  ethernets:"
}

while IFS=, read -r name ip role; do
  [[ -z "${name// }" || "$name" == \#* ]] && continue
  fabric_if="$(field "$IFACES" "$name" 2)"
  campus_if="$(field "$IFACES" "$name" 3)"
  [[ -n "$fabric_if" ]] || { echo "no fabric_if for $name in interfaces.csv" >&2; exit 1; }
  out="$HERE/$name.yaml"

  if [[ "$role" == "controller" ]]; then
    [[ -n "$campus_if" ]] || { echo "no campus_if for $name in interfaces.csv" >&2; exit 1; }
    {
      header
      echo "    $campus_if:                       # campus uplink — keep 1500, owns the default route"
      echo "      dhcp4: true"
      echo "      dhcp6: false"
      echo "      accept-ra: false"
      echo "      mtu: 1500"
      echo "    $fabric_if:                       # cluster fabric — jumbo frames, no gateway"
      echo "      dhcp4: false"
      echo "      dhcp6: false"
      echo "      accept-ra: false"
      echo "      link-local: []"
      echo "      addresses: [$ip/24]"
      echo "      mtu: 9000"
      if [[ "$OOB" == "1" ]]; then
        echo "  vlans:"
        echo "    $fabric_if.9:                     # net-oob: switch management, anchor only"
        echo "      id: 9"
        echo "      link: $fabric_if"
        echo "      dhcp4: false"
        echo "      accept-ra: false"
        echo "      link-local: []"
        echo "      addresses: [$OOB_ADDR]"
        echo "      mtu: 1500"
      fi
    } > "$out"
  else
    {
      header
      echo "    $fabric_if:"
      echo "      dhcp4: false"
      echo "      dhcp6: false"
      echo "      accept-ra: false"
      echo "      link-local: []"
      echo "      addresses: [$ip/24]"
      echo "      mtu: 9000"
      echo "      routes:"
      echo "        - to: default"
      echo "          via: $ANCHOR_IP             # anchor NAT gateway (ADR-N6)"
      echo "      nameservers:"
      echo "        addresses: [$ANCHOR_IP]"
      echo "        search: [$DOMAIN]"
    } > "$out"
  fi
  echo "wrote $out"
done < "$NODES"
