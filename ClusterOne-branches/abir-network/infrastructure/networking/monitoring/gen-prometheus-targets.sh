#!/usr/bin/env bash
# gen-prometheus-targets.sh — scrape config generated from inventory/nodes.csv (N6).
#
#   gen-prometheus-targets.sh [nodes.csv] > network-scrape.yml
#
# Emits scrape_configs for node_exporter, DCGM (compute only), and the blackbox
# icmp / ssh / dns probes. Merge into prometheus.yml (or use `scrape_config_files:`).
# Generated from the CSV so a node added to the inventory is monitored with no hand edit.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CSV="${1:-$HERE/../inventory/nodes.csv}"
[[ -r "$CSV" ]] || { echo "cannot read $CSV" >&2; exit 1; }

all=(); compute=()
while IFS=, read -r name ip role; do
  [[ -z "$name" || "$name" == \#* || "$name" == shortname ]] && continue
  all+=("$ip"); [[ "$role" == compute ]] && compute+=("$ip")
done < "$CSV"

targets() { local p="$1"; shift; local s=""; for i in "$@"; do s="$s${s:+, }\"$i$p\""; done; printf '%s' "$s"; }

cat <<EOF
# GENERATED by gen-prometheus-targets.sh — do not edit by hand.
scrape_configs:
  - job_name: node
    static_configs:
      - targets: [$(targets :9100 "${all[@]}")]

  - job_name: dcgm
    static_configs:
      - targets: [$(targets :9400 "${compute[@]}")]

  - job_name: blackbox-icmp
    metrics_path: /probe
    params: {module: [icmp]}
    static_configs:
      - targets: [$(targets "" "${all[@]}")]
    relabel_configs: &bb
      - source_labels: [__address__]
        target_label: __param_target
      - source_labels: [__param_target]
        target_label: instance
      - target_label: __address__
        replacement: 127.0.0.1:9115

  - job_name: blackbox-ssh
    metrics_path: /probe
    params: {module: [tcp_ssh]}
    static_configs:
      - targets: [$(targets :22 "${all[@]}")]
    relabel_configs: *bb

  - job_name: blackbox-dns
    metrics_path: /probe
    params: {module: [dns_anchor]}
    static_configs:
      - targets: ["10.42.0.10"]
    relabel_configs: *bb
EOF
