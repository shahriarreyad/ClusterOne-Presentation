#!/usr/bin/env bash
# egress-allowlist.sh — build and load the N8.2 egress allowlist on anchor01.
#
#   egress-allowlist.sh [--domains FILE] [--out FILE] [--temp-web-until YYYY-MM-DD] [--no-load]
#
# Resolves egress-domains.txt to IPv4, writes an nft include file that defines the
# `egress_v4` set + the egress_policy chain, validates it with `nft -c`, installs it
# atomically and reloads only that chain. Run by clusterone-egress-refresh.timer.
#
# --temp-web-until: keep a visible, DATED "allow tcp 80/443" rule until that day, because
# CDN IPs rotate faster than any static list (N8.2). After the date the rule is dropped
# automatically and the script warns loudly — it can never become quietly permanent.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOMAINS="$HERE/egress-domains.txt"
OUT="/etc/nftables.d/clusterone-egress.nft"
TEMP_UNTIL=""
LOAD=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domains) DOMAINS="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --temp-web-until) TEMP_UNTIL="$2"; shift 2 ;;
    --no-load) LOAD=0; shift ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
[[ -r "$DOMAINS" ]] || { echo "cannot read $DOMAINS" >&2; exit 1; }

ips=""
while read -r d; do
  [[ -z "$d" || "$d" == \#* ]] && continue
  found="$(getent ahostsv4 "$d" 2>/dev/null | awk '{print $1}' | sort -u || true)"
  if [[ -z "$found" ]]; then echo "warn: $d did not resolve" >&2; continue; fi
  ips="$ips"$'\n'"$found"
done < "$DOMAINS"
ips="$(printf '%s\n' "$ips" | sed '/^$/d' | sort -u)"
[[ -n "$ips" ]] || { echo "no domain resolved — refusing to install an empty allowlist" >&2; exit 1; }

tmp="$(mktemp)"
{
  echo "# GENERATED by egress-allowlist.sh at $(date -Is) — do not edit."
  echo "add set inet clusterone egress_v4 { type ipv4_addr; flags interval; }"
  echo "flush set inet clusterone egress_v4"
  echo "add element inet clusterone egress_v4 { $(printf '%s\n' "$ips" | paste -sd, - | sed 's/,/, /g') }"
  echo "flush chain inet clusterone egress_policy"
  echo "add rule inet clusterone egress_policy ip daddr @egress_v4 tcp dport { 80, 443 } counter accept comment \"egress allowlist\""
  if [[ -n "$TEMP_UNTIL" ]]; then
    if [[ "$(date +%Y-%m-%d)" < "$TEMP_UNTIL" ]]; then
      echo "add rule inet clusterone egress_policy tcp dport { 80, 443 } counter accept comment \"TEMP until $TEMP_UNTIL: review in N9\""
    else
      echo "warn: temp web rule expired on $TEMP_UNTIL — allowlist only" >&2
    fi
  fi
} > "$tmp"

if command -v nft >/dev/null; then
  # nft -c only proves the syntax against a live table; skip the check when it is absent
  if nft list table inet clusterone >/dev/null 2>&1; then nft -c -f "$tmp"; fi
fi

install -D -m 0644 "$tmp" "$OUT"
rm -f "$tmp"
echo "wrote $OUT ($(printf '%s\n' "$ips" | wc -l | tr -d ' ') addresses)"
(( LOAD )) && nft -f "$OUT" && echo "egress_policy reloaded"
exit 0
