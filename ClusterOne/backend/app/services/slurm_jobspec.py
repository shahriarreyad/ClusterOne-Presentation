"""Turn a validated job into a slurmrestd submission.

Execution model: the batch script runs `apptainer exec` on the allocated GPU
node and nothing else user-controlled runs on the host. Every user-supplied
value is validated (app.validation) and then single-quoted with shlex.quote
before it is placed in the script, so it can never be parsed as shell syntax or
as an extra #SBATCH directive. The user's command is handed to
`/bin/bash -c` *inside* the container as a single argument.

Written from the slurmrestd v0.0.40 schema documentation; it has not been
exercised against a live slurmrestd (see README, "What needs a real cluster").
"""
import shlex
from typing import Any, Dict, List, Optional

from app.config import settings
from app.models import Job
from app.utils import format_slurm_time

DEFAULT_OUTPUT_NAME = "clusterone-%j.out"


def default_output_dir(job: Job) -> str:
    """Where a job writes when the user gave no output_dir: their home directory.

    Slurm opens the stdout file before the script runs, so this directory has to
    exist already; a user's home does (Keycloak username == POSIX username).
    """
    return f"{settings.nfs_home_root.rstrip('/')}/{job.submitted_by}"


def effective_output_dir(job: Job) -> str:
    return job.output_dir or default_output_dir(job)


def output_pattern(job: Job) -> str:
    return f"{effective_output_dir(job)}/{DEFAULT_OUTPUT_NAME}"


def build_script(job: Job, node_name: Optional[str] = None, exclude: Optional[List[str]] = None) -> str:
    """node_name: a registered hostname the user chose (validated at registration); adds --nodelist."""
    q = shlex.quote
    gpus = job.gpus_wanted()
    out_dir = effective_output_dir(job)
    work_dir = job.working_dir or out_dir
    image = job.image or settings.default_image
    command = job.command or job.script or "echo 'no command given'"

    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={job.name}",
        f"#SBATCH --partition={job.partition or settings.slurm_default_partition}",
        "#SBATCH --nodes=1",
        "#SBATCH --ntasks=1",
        f"#SBATCH --cpus-per-task={job.cpu_cores}",
        f"#SBATCH --mem={job.ram_mb}M",
        f"#SBATCH --time={format_slurm_time(job.time_limit_minutes or 60)}",
        f"#SBATCH --output={output_pattern(job)}",
    ]
    if gpus:
        lines.append(f"#SBATCH --gres=gpu:{gpus}")
    if node_name:
        lines.append(f"#SBATCH --nodelist={q(node_name)}")
    if exclude:  # nodes whole-reserved by other users
        lines.append(f"#SBATCH --exclude={','.join(q(n) for n in exclude)}")
    lines += [
        "",
        "# Generated by ClusterOne. Everything below the line is data, not shell syntax.",
        f"CLUSTERONE_IMAGE={q(image)}",
        f"CLUSTERONE_WORKDIR={q(work_dir)}",
        f"CLUSTERONE_OUTPUT_DIR={q(out_dir)}",
        f"CLUSTERONE_COMMAND={q(command)}",
        f"export APPTAINERENV_CLUSTERONE_JOB_ID={q(job.id)}",
        'export APPTAINERENV_CLUSTERONE_OUTPUT_DIR="$CLUSTERONE_OUTPUT_DIR"',
        'export APPTAINERENV_OMP_NUM_THREADS="${SLURM_CPUS_PER_TASK:-1}"',
        'export APPTAINERENV_SLURM_JOB_ID="${SLURM_JOB_ID:-}"',
        # Slurm's GPU binding must survive --cleanenv.
        '[ -n "${CUDA_VISIBLE_DEVICES:-}" ] && export APPTAINERENV_CUDA_VISIBLE_DEVICES="$CUDA_VISIBLE_DEVICES"',
    ]
    binds = ["$CLUSTERONE_WORKDIR"]
    if out_dir != work_dir:
        binds.append("$CLUSTERONE_OUTPUT_DIR")
    if job.dataset_path:
        lines += [f"CLUSTERONE_DATASET={q(job.dataset_path)}",
                  'export APPTAINERENV_CLUSTERONE_DATASET_DIR="$CLUSTERONE_DATASET"']
        binds.append("$CLUSTERONE_DATASET:$CLUSTERONE_DATASET:ro")
    for key, value in sorted((job.env_vars or {}).items()):
        lines.append(f"export APPTAINERENV_{key}={q(value)}")

    nv = " --nv" if gpus else ""
    bind_arg = ",".join(b if ":" in b else f"{b}:{b}" for b in binds)
    lines += [
        "",
        'mkdir -p "$CLUSTERONE_OUTPUT_DIR"',
        'cd "$CLUSTERONE_WORKDIR" || exit 1',
        # Timestamp each output line with the bash builtin (no extra processes).
        "ts_filter() { while IFS= read -r l || [ -n \"$l\" ]; do printf '%(%Y-%m-%dT%H:%M:%S%z)T %s\\n' -1 \"$l\"; done; }",
        "set -o pipefail",
        # The first output lines record, from the node itself, where the job really ran and
        # which GPUs Slurm gave it. The group's exit status is apptainer's (its last command).
        "{",
        '  echo "[clusterone] executing on $(hostname), Slurm job ${SLURM_JOB_ID:-?}, '
        f'GPUs requested: {gpus}, CUDA_VISIBLE_DEVICES=${{CUDA_VISIBLE_DEVICES:-unset}}"',
        *(['  command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L'] if gpus else []),
        f'  apptainer exec{nv} --cleanenv --pwd "$CLUSTERONE_WORKDIR" --bind "{bind_arg}" '
        '"$CLUSTERONE_IMAGE" /bin/bash -c "$CLUSTERONE_COMMAND"',
        "} 2>&1 | ts_filter",
        "rc=${PIPESTATUS[0]}",
        "exit $rc",
        "",
    ]
    return "\n".join(lines)


def build_submission(job: Job, node_name: Optional[str] = None, exclude: Optional[List[str]] = None) -> Dict[str, Any]:
    """Body for POST /slurm/<ver>/job/submit. node_name pins the job to one node (Slurm's node name)."""
    gpus = job.gpus_wanted()
    spec: Dict[str, Any] = {
        "name": job.name,
        "partition": job.partition or settings.slurm_default_partition,
        "nodes": "1",
        "tasks": 1,
        "cpus_per_task": job.cpu_cores,
        "memory_per_node": {"set": True, "infinite": False, "number": job.ram_mb},
        "time_limit": {"set": True, "infinite": False, "number": job.time_limit_minutes or 60},
        "current_working_directory": job.working_dir or effective_output_dir(job),
        "standard_output": output_pattern(job),
        "comment": f"clusterone job={job.id} user={job.submitted_by}",
        # slurmrestd does not parse #SBATCH lines, so the same limits are also given
        # structurally above. Environment is deliberately minimal: user variables
        # travel inside the (quoted) script and reach only the container.
        "environment": ["PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"],
    }
    if gpus:
        spec["tres_per_node"] = f"gres:gpu:{gpus}"
    if node_name:
        spec["required_nodes"] = [node_name]  # field spelling per the v0.0.40 docs; verify on your Slurm version
    if exclude:
        spec["excluded_nodes"] = list(exclude)  # field spelling per the v0.0.40 docs; verify on your Slurm version
    return {"job": spec, "script": build_script(job, node_name, exclude)}


def extract_job_id(result: Dict[str, Any]) -> Optional[str]:
    """slurmrestd answers a submit with job_id at the top level (v0.0.40) or nested."""
    job_id = result.get("job_id")
    if job_id is None:
        jobs = result.get("result") or {}
        job_id = jobs.get("job_id") if isinstance(jobs, dict) else None
    return str(job_id) if job_id not in (None, "", 0) else None
